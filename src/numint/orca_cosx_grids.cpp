// ORCA 6.1 COSX (GRIDX 1/2/3) atomic grids, measured from ORCA 6.1.1.
//
// For every element H-Rn, ORCA 6.1.1 was run on the free atom
// (HF/def2-SVP, RIJCOSX) and the COSX grids it writes (<base>.gridxN.tmp:
// points, weights, partition weights) were read back. Every grid is exactly a
// Perez-Jorda Gauss-Chebyshev radial quadrature with the M3 mapping
// r = xi / ln2 * ln(2 / (1 - x)) -- ORCA prints it as "OptM3 with GC (2021)"
// -- times Lebedev grids that change from shell to shell. Radii and weights
// reproduce ORCA's to 2e-10 and 2e-9 relative with the xi below.
//
// What the measurements show (and the tables encode):
//  * The grid is a property of the element and level only: def2-SVP and
//    def2-TZVP give identical grids; there is no IntAcc formula behind the
//    radial counts (C: 26/34/42 shells, H: 21/27/33).
//  * xi is element- and level-specific (for rows 1-3 xi(level) = s(row,
//    level) * xi(level 1)).
//  * The angular "adaptive" pruning is a fixed shell profile per period and
//    level, already reduced one level for H/He.
//  * Na-Ar use the GRIDX 2 grid for GRIDX 1, and K-Rn use a single grid for
//    all three levels.
