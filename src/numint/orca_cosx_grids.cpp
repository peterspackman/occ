OrcaCOSXAtomicGrid orca_cosx_atomic_grid(int atomic_number, int level) {
  OrcaCOSXAtomicGrid result;
  if (atomic_number < 1 || atomic_number > static_cast<int>(kElements.size()) ||
      level < 1 || level > 3)
    return result;
  const auto &e = kElements[atomic_number - 1][level - 1];
  result.num_radial = e.num_radial;
  result.xi = e.xi;
  result.angular_runs = &kProfiles[e.profile];
  return result;
}

